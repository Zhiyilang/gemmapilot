#!/usr/bin/env python3
"""
make_repro.py — scaffold a MINIMAL failing test that reproduces the reported bug.

WHY THIS EXISTS
The single most common failure mode of a coding agent is patching before it can
see the failure. A reproduction converts "the issue says it's broken" into an
observable, executable fact:

    RED   (repro fails on the unpatched repo)  -> the bug is real and localized
    GREEN (repro passes after the patch)       -> the fix actually addresses it

Skipping RED is how agents "fix" the wrong thing and burn the whole 12 h budget.

WHAT IT DOES
Emits a small pytest file asserting `--expr == --expect`, then optionally RUNS
the test without pytest (`--run`), which is useful in stripped environments.

USAGE
  python skills/reproduce/scripts/make_repro.py \
      --out tests/test_repro_42.py --module fastapi.routing \
      --expr "add(2, 3)" --expect "5" --syspath /workspace

  python ... --run            # also execute it and print RED/GREEN
  python ... --run --json     # machine-readable verdict

Stdlib only. Refuses to write syntactically invalid Python.
"""
from __future__ import annotations
import argparse, ast, json, os, sys, importlib.util, traceback

TEMPLATE = '''"""
Auto-generated reproduction for: {name}
Generated by skills/reproduce/scripts/make_repro.py — safe to delete.
"""
import os
import sys

sys.path.insert(0, {syspath!r})

{imports}


def {test_name}():
    assert ({expr}) == ({expect}), (
        "reproduction failed: {expr!r} != {expect!r}"
    )
'''


def validate_python(src: str, what: str):
    try:
        ast.parse(src, mode="exec")
    except SyntaxError as e:
        raise SystemExit(f"[make_repro] {what} is not valid Python: {e}\n  got: {src!r}")


def build_file(args) -> str:
    validate_python(args.expr, "--expr")
    validate_python(args.expect, "--expect")
    imports = ""
    if args.module:
        validate_python(f"import {args.module}", "--module")
        # BOTH forms are required: `import x` gives x.qualified access, while
        # `from x import *` is what makes BARE names in --expr resolve. Emitting
        # only the first is a silent bug: the generated test raises NameError
        # and the agent concludes "cannot reproduce" when the bug is real.
        imports = (f"import {args.module}\n"
                   f"from {args.module} import *  # noqa: F401,F403 "
                   f"— bare names used in the assertion")
    for extra in [x for x in (args.imports or "").split(",") if x.strip()]:
        validate_python(f"import {extra.strip()}", "--imports")
        imports += f"\nimport {extra.strip()}"
    return TEMPLATE.format(
        name=args.name.replace('"', "'"),
        syspath=args.syspath,
        imports=imports,
        test_name=args.test_name,
        expr=args.expr,
        expect=args.expect,
    )


def run_file(path: str, test_name: str) -> dict:
    """Execute the generated test WITHOUT pytest (works in bare environments)."""
    spec = importlib.util.spec_from_file_location("_repro_" + test_name, path)
    if spec is None or spec.loader is None:
        return {"verdict": "ERROR", "detail": "cannot import generated file"}
    mod = importlib.util.module_from_spec(spec)
    try:
        spec.loader.exec_module(mod)
        getattr(mod, test_name)()
        return {"verdict": "GREEN", "detail": "assertion held"}
    except AssertionError as e:
        return {"verdict": "RED", "detail": f"AssertionError: {e}"}
    except Exception as e:
        return {"verdict": "ERROR", "detail": f"{type(e).__name__}: {e}\n"
                                              + traceback.format_exc(limit=3)}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--module", default="", help="dotted module to import, e.g. fastapi.routing")
    ap.add_argument("--expr", required=True, help="expression expected to be wrong today")
    ap.add_argument("--expect", required=True, help="the correct value (Python literal)")
    ap.add_argument("--imports", default="", help="extra modules, comma separated")
    ap.add_argument("--syspath", default="/workspace")
    ap.add_argument("--name", default="reproduction")
    ap.add_argument("--test-name", default="test_repro")
    ap.add_argument("--force", action="store_true", help="overwrite if exists")
    ap.add_argument("--run", action="store_true", help="execute after writing")
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args()

    src = build_file(a)
    if os.path.exists(a.out) and not a.force:
        raise SystemExit(f"[make_repro] {a.out} exists; pass --force to overwrite")
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w", encoding="utf-8") as f:
        f.write(src)

    result = {"written": a.out}
    if a.run:
        result.update(run_file(a.out, a.test_name))
        v = result["verdict"]
        result["meaning"] = {
            "RED": "bug reproduced — safe to patch now",
            # GREEN means opposite things depending on WHEN it is run — spell
            # that out, otherwise the agent misreads a successful fix as
            # "no bug" (or worse, patches a non-existent defect).
            "GREEN": "assertion held. BEFORE patching: the reported bug does NOT "
                     "reproduce — re-read the issue or the expression, do NOT "
                     "patch blindly. AFTER patching: the fix works.",
            "ERROR": "the repro could not run (import/path problem), "
                     "not evidence about the bug",
        }[v]

    print(json.dumps(result, ensure_ascii=False, indent=2) if a.json else
          "\n".join(f"{k}: {v}" for k, v in result.items()))
    # exit 0 always: RED is a successful reproduction, not a tool failure.
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
